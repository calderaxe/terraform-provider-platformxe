package resources

import (
	"context"

	"github.com/hashicorp/terraform-plugin-framework/resource"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/booldefault"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/planmodifier"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/stringplanmodifier"
	"github.com/hashicorp/terraform-plugin-framework/types"

	platformxe "github.com/calderaxe/platformxe-go"
)

var _ resource.Resource = &WebhookResource{}
var _ resource.ResourceWithConfigure = &WebhookResource{}

type WebhookResource struct {
	client *platformxe.Client
}

type WebhookResourceModel struct {
	ID       types.String `tfsdk:"id"`
	Name     types.String `tfsdk:"name"`
	URL      types.String `tfsdk:"url"`
	Events   types.List   `tfsdk:"events"`
	IsActive types.Bool   `tfsdk:"is_active"`
	Secret   types.String `tfsdk:"secret"`
}

func NewWebhooksEndpointResource() resource.Resource {
	return &WebhookResource{}
}

func (r *WebhookResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_webhooks_endpoint"
}

func (r *WebhookResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		Description: "Manages a PlatformXe webhook endpoint.",
		Attributes: map[string]schema.Attribute{
			"id": schema.StringAttribute{
				Computed:    true,
				Description: "Webhook identifier.",
				PlanModifiers: []planmodifier.String{
					stringplanmodifier.UseStateForUnknown(),
				},
			},
			"name": schema.StringAttribute{
				Required:    true,
				Description: "Webhook display name.",
			},
			"url": schema.StringAttribute{
				Required:    true,
				Description: "Webhook delivery URL (HTTPS).",
			},
			"events": schema.ListAttribute{
				Required:    true,
				ElementType: types.StringType,
				Description: "List of event types to subscribe to.",
			},
			"is_active": schema.BoolAttribute{
				Optional:    true,
				Computed:    true,
				Default:     booldefault.StaticBool(true),
				Description: "Whether the webhook is active (status ACTIVE) or paused (PAUSED). Defaults to true.",
			},
			"secret": schema.StringAttribute{
				Computed:    true,
				Sensitive:   true,
				Description: "Webhook signing secret (generated by PlatformXe).",
				PlanModifiers: []planmodifier.String{
					stringplanmodifier.UseStateForUnknown(),
				},
			},
		},
	}
}

func (r *WebhookResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}
	client, ok := req.ProviderData.(*platformxe.Client)
	if !ok {
		resp.Diagnostics.AddError("Unexpected Resource Configure Type", "Expected *platformxe.Client")
		return
	}
	r.client = client
}

func (r *WebhookResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan WebhookResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	var events []string
	resp.Diagnostics.Append(plan.Events.ElementsAs(ctx, &events, false)...)
	if resp.Diagnostics.HasError() {
		return
	}

	input := map[string]interface{}{
		"name":   plan.Name.ValueString(),
		"url":    plan.URL.ValueString(),
		"events": events,
	}

	result, err := r.client.Webhooks.Create(input)
	if err != nil {
		resp.Diagnostics.AddError("Create Webhook Failed", err.Error())
		return
	}

	plan.ID = types.StringValue(result.ID)
	plan.Secret = types.StringValue(result.Secret)

	// A new endpoint is always ACTIVE; pausing it is a second call.
	if !plan.IsActive.ValueBool() {
		if _, err := r.client.Webhooks.Update(result.ID, map[string]interface{}{"status": "PAUSED"}); err != nil {
			// Keep the created endpoint (and its one-time secret) in state;
			// the next apply retries the pause.
			plan.IsActive = types.BoolValue(true)
			resp.Diagnostics.Append(resp.State.Set(ctx, plan)...)
			resp.Diagnostics.AddError("Pause Webhook Failed", err.Error())
			return
		}
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, plan)...)
}

func (r *WebhookResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state WebhookResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	result, err := r.client.Webhooks.Get(state.ID.ValueString())
	if err != nil {
		resp.Diagnostics.AddError("Read Webhook Failed", err.Error())
		return
	}

	state.Name = types.StringValue(result.Name)
	state.URL = types.StringValue(result.URL)
	// FAILING is still a live endpoint; only PAUSED is inactive.
	state.IsActive = types.BoolValue(result.Status != "PAUSED")

	listVal, diags := types.ListValueFrom(ctx, types.StringType, result.Events)
	resp.Diagnostics.Append(diags...)
	state.Events = listVal

	resp.Diagnostics.Append(resp.State.Set(ctx, state)...)
}

func (r *WebhookResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan WebhookResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	var events []string
	resp.Diagnostics.Append(plan.Events.ElementsAs(ctx, &events, false)...)
	if resp.Diagnostics.HasError() {
		return
	}

	status := "ACTIVE"
	if !plan.IsActive.ValueBool() {
		status = "PAUSED"
	}
	input := map[string]interface{}{
		"name":   plan.Name.ValueString(),
		"url":    plan.URL.ValueString(),
		"events": events,
		"status": status,
	}

	_, err := r.client.Webhooks.Update(plan.ID.ValueString(), input)
	if err != nil {
		resp.Diagnostics.AddError("Update Webhook Failed", err.Error())
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, plan)...)
}

func (r *WebhookResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state WebhookResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	_, err := r.client.Webhooks.Delete(state.ID.ValueString())
	if err != nil {
		resp.Diagnostics.AddError("Delete Webhook Failed", err.Error())
		return
	}
}
